"""Print the README's result tables as Markdown, straight from artifacts/metrics.json.

    python scripts/make_readme_tables.py                  # print to stdout
    python scripts/make_readme_tables.py --inject README.md   # replace the block between the RESULTS markers
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.automata.languages import LANGUAGES  # noqa: E402

import contextlib
import io

m = json.loads((ROOT / "artifacts" / "metrics.json").read_text(encoding="utf-8"))
_buffer = io.StringIO()
_redirect = contextlib.redirect_stdout(_buffer)
_redirect.__enter__()
P = ["lr", "dt", "rf", "stack"]
PN = {"lr": "LR", "dt": "DT", "rf": "RF", "stack": "Stack"}
L = list(LANGUAGES)


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


langs = {x["id"]: x for x in m["languages"]}
print("### Languages\n")
print(
    table(
        ["id", "language", "alphabet", "regular expression", "minimal DFA", "NFA", "subset DFA"],
        [
            [
                lid,
                LANGUAGES[lid].name.replace("|", "\\|"),
                "{" + ",".join(LANGUAGES[lid].alphabet) + "}",
                "`" + LANGUAGES[lid].regex.replace("|", "\\|") + "`",
                str(langs[lid]["truth"]["minimized states (after)"]),
                f"{langs[lid]['truth']['NFA states']}" + (" (ε)" if langs[lid]["truth"]["ε-moves"] else ""),
                str(langs[lid]["truth"]["subset DFA states (before)"]),
            ]
            for lid in L
        ],
    )
)

print("\n### ML pipelines: test accuracy / accuracy on unseen lengths 21-40\n")
print(
    table(
        ["language", *[PN[p] for p in P], "best pipeline (test F1)"],
        [
            [
                lid,
                *[f"{m['ml'][lid][p]['test']['accuracy']:.3f} / {m['ml'][lid][p]['long']['accuracy']:.3f}" for p in P],
                f"{PN[m['summary']['best_pipeline_per_language'][lid]['pipeline']]} ({m['summary']['best_pipeline_per_language'][lid]['test_f1']:.3f})",
            ]
            for lid in L
        ],
    )
)

avg = m["summary"]["pipeline_averages"]
print("\n### Mean over the ten languages\n")
print(
    table(
        ["pipeline", "val acc", "val F1", "test acc", "test precision", "test recall", "test F1", "long acc"],
        [
            [
                PN[p],
                f"{avg['val'][p]['accuracy']:.3f}",
                f"{avg['val'][p]['f1']:.3f}",
                f"{avg['test'][p]['accuracy']:.3f}",
                f"{avg['test'][p]['precision']:.3f}",
                f"{avg['test'][p]['recall']:.3f}",
                f"{avg['test'][p]['f1']:.3f}",
                f"{avg['long'][p]['accuracy']:.3f}",
            ]
            for p in P
        ],
    )
)

print("\n### Learned automata: states after minimization (✓ = exactly equivalent to the ground truth)\n")
A = ["lstar_lr", "lstar_dt", "lstar_rf", "lstar_stack", "rpni", "edsm"]
AN = {"lstar_lr": "L*·LR", "lstar_dt": "L*·DT", "lstar_rf": "L*·RF", "lstar_stack": "L*·Stack", "rpni": "RPNI", "edsm": "EDSM"}
rows = []
for lid in L:
    row = [lid, str(m["automata"][lid]["dfa"]["states"])]
    for a in A:
        r = m["automata"][lid][a]
        mark = "✓" if r["equivalent_to_truth"] else f"✗ `{r['counterexample_to_truth'] or 'ε'}`"
        conv = "" if r.get("converged", True) else "*"
        row.append(f"{r['states']}{conv} {mark}")
    rows.append(row)
print(table(["language", "truth", *[AN[a] for a in A]], rows))
print("\n`*` = L* stopped at its 64-state budget (did not converge); `✗ w` = shortest string on which the DFA and the ground truth disagree.")

print("\n### Ground truth vs learned DFAs vs ML pipelines (means over the ten languages)\n")
print(
    table(
        ["approach", "test acc", "long acc", "drop", "size", "µs / string", "build time (s)", "exact languages"],
        [
            [
                r["approach"],
                f"{r['test_accuracy']:.3f}",
                f"{r['long_accuracy']:.3f}",
                f"{0.0 if abs(r['generalization_drop']) < 5e-4 else r['generalization_drop']:+.3f}",
                f"{r['mean_size']:,.1f} {'transitions' if r['size_unit'] == 'transitions' else 'params/nodes'}",
                f"{r['inference_us_per_string']:.2f}",
                "–" if r["build_time_s"] is None else f"{r['build_time_s']:.3f}",
                str(r["exact_languages"]) if r["family"] != "ML pipeline" else "–",
            ]
            for r in m["summary"]["comparison_overall"]
        ],
    )
)

print("\n### Insights (generated by notebook 02)\n")
for line in m["summary"]["insights"]:
    print(f"- {line}")

_redirect.__exit__(None, None, None)
_tables = _buffer.getvalue()
if len(sys.argv) == 3 and sys.argv[1] == "--inject":
    target = Path(sys.argv[2])
    text = target.read_text(encoding="utf-8")
    start, end = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    target.write_text(head + start + "\n" + _tables.rstrip() + "\n" + end + tail, encoding="utf-8", newline="\n")
    print(f"injected results into {target}")
else:
    sys.stdout.write(_tables)
